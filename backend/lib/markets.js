export function lookupMarket(name, { source } = {}) {
  const n = String(name || '').trim();
  if (!n) return null;
  // 台中零售訪價：資料集本身限臺中市公有零售市場，市場可辨識為臺中市
  if (source === 'taichung_retail') return { county: '臺中市', region: 'central' };
  const county = MARKET_COUNTY[n] || MARKET_COUNTY[n.replace(/^臺/, '台')] || null;
  if (!county) return null;
  return { county, region: COUNTY_REGION[county] || null };
}
